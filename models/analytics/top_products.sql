WITH clean AS (
    SELECT * FROM {{ ref('clean_sales') }}
)

SELECT
    STOCKCODE,
    DESCRIPTION,
    SUM(REVENUE)                AS TOTAL_REVENUE,
    SUM(QUANTITY)               AS TOTAL_QUANTITY_SOLD,
    COUNT(DISTINCT INVOICENO)   AS TOTAL_ORDERS
FROM clean
GROUP BY STOCKCODE, DESCRIPTION
ORDER BY TOTAL_REVENUE DESC
LIMIT 10
