WITH staged AS (
    SELECT * FROM {{ ref('stg_raw_sales') }}
),

cleaned AS (
    SELECT
        INVOICENO,
        STOCKCODE,
        UPPER(TRIM(DESCRIPTION))        AS DESCRIPTION,
        QUANTITY,
        TO_TIMESTAMP(INVOICEDATE, 'MM/DD/YYYY HH24:MI:SS') AS INVOICEDATE_TS,
        TO_DATE(INVOICEDATE, 'MM/DD/YYYY HH24:MI:SS')      AS INVOICE_DATE_ONLY,
        YEAR(TO_TIMESTAMP(INVOICEDATE, 'MM/DD/YYYY HH24:MI:SS'))  AS YEAR,
        MONTH(TO_TIMESTAMP(INVOICEDATE, 'MM/DD/YYYY HH24:MI:SS')) AS MONTH,
        UNITPRICE,
        CUSTOMERID,
        UPPER(TRIM(COUNTRY))            AS COUNTRY,
        REVENUE,
        LOADED_AT
    FROM staged
)

SELECT * FROM cleaned